    private void Report(string text)
    {
        if (_status != null)
        {
            _status.Text = text ?? "";
        }

        if (text != null)
        {
            GD.Print($"[GUO editor] staticstudio: {text}");
        }
    }

    // --- target -----------------------------------------------------------------

    private void BindTarget()
    {
        Inspection ins = _source();
        if (ins?.ArtKind == null)
        {
            Report("nothing to bind: pick art or a gump in the UO Inspector");
            return;
        }

        _targetKind = ins.ArtKind;
        _targetId = ins.ArtId;
        _target.Text = $"{ArtSidecar.KindName(ins.ArtKind.Value)} 0x{ins.ArtId:X4}";
        Report($"bound {_target.Text}");
    }

    /// <summary>Binds a target without the UI (the smoke check).</summary>
    public void BindTarget(AssetKind kind, int id, Image image)
    {
        _targetKind = kind;
        _targetId = id;
        _boundImage = image;
        if (_target != null)
        {
            _target.Text = $"{ArtSidecar.KindName(kind)} 0x{id:X4}";
        }
    }

    /// <summary>Runs an image request on a worker and files the gallery (the smoke check).</summary>
    public async Task<ImageResult> RunImageAsync(IImageProvider provider, ImageRequest req)
    {
        ImageResult r = await Task.Run(() => provider.RunAsync(req, null, _cts.Token));
        Finish(r);
        return r;
    }

    private Image _boundImage;

    // --- image jobs (the Art dock's providers) -----------------------------------

    private void RefreshWorkflows()
    {
        _workflowPick.Clear();
        foreach (string f in ComfyUiProvider.Workflows(ArtDock.WorkflowFolder))
        {
            _workflowPick.AddItem(Path.GetFileName(f));
            _workflowPick.SetItemMetadata(_workflowPick.ItemCount - 1, f);
        }

        if (_workflowPick.ItemCount == 0)
        {
            _workflowPick.AddItem("(no workflows: put API-format .json files in the workflow folder)");
            _workflowPick.Disabled = true;
        }
        else
        {
            _workflowPick.Disabled = false;
        }
    }

    private async Task QueueFromUi()
    {
        string url = EditorData.Setting("UO_COMFY_URL", "http://127.0.0.1:8188");
        var provider = new ComfyUiProvider(url);
        string wf = _workflowPick.ItemCount > 0 && !_workflowPick.Disabled
            ? (string)_workflowPick.GetItemMetadata(_workflowPick.Selected) : "";
        ImageRequest req = BuildRequest(_prompt.Text, wf);
        if (req == null)
        {
            return;
        }

        Report($"queued on {provider.Name}...");
        ImageResult r = await Task.Run(() => provider.RunAsync(req, null, _cts.Token));
        Finish(r);
        Report(r.Error ?? $"{r.Pngs.Count} image(s) ready; pick one and save it as a theme variant");
        provider.Dispose();
    }

    /// <summary>The request for a prompt, a workflow file and the bound static as input.</summary>
    public ImageRequest BuildRequest(string prompt, string workflowPath)
    {
        if (_targetKind == null)
        {
            Report("no target: bind a static first");
            return null;
        }

        Image img = _boundImage ?? _source()?.Image;
        if (img == null)
        {
            Report("no pixels for the bound static: show it in the UO Inspector");
            return null;
        }

        return new ImageRequest
        {
            Prompt = prompt ?? "",
            WorkflowPath = workflowPath ?? "",
            InputPng = img.SavePngToBuffer(),
            InputName = $"client:{ArtSidecar.KindName(_targetKind.Value)}:0x{_targetId:X4}",
            InputIsClientArt = true,
            Width = img.GetWidth(),
            Height = img.GetHeight(),
        };
    }

    private void Finish(ImageResult r)
    {
        _lastResult = r;
        _lastWorkflow = r.Workflow;
        _lastSeed = r.Seed;
        _images.Clear();
        _gallery?.Clear();
        foreach (byte[] png in r.Pngs)
        {
            var img = new Image();
            if (img.LoadPngFromBuffer(png) == Error.Ok)
            {
                _images.Add(img);
                _gallery?.AddItem($"{img.GetWidth()}x{img.GetHeight()}", ImageTexture.CreateFromImage(img));
            }
        }

        if (_gallery != null && _images.Count > 0)
        {
            _gallery.Select(0);
        }
    }

    // --- theme variants ----------------------------------------------------------

    /// <summary>Where this world project's themes live (created on first save).</summary>
    public static string ThemeDir(EditorData data)
    {
        string root = null;
        try
        {
            root = data?.Assets?.Root;
        }
        catch (Exception)
        {
        }

        return Path.Combine(root ?? EditorData.RepoRoot, "themes");
    }

    /// <summary>
    /// Saves the selected gallery image as a theme variant: overlay PNG at a
    /// free static id plus a theme entry mapping the bound graphic at it.
    /// Returns a status line (the reason when it did not save).
    /// </summary>
    public string SaveVariant(int index = -1, string theme = null)
    {
        if (_data?.Assets == null)
        {
            return "no world project is open";
        }

        if (index < 0)
        {
            int[] sel = _gallery?.GetSelectedItems() ?? System.Array.Empty<int>();
            index = sel.Length > 0 ? sel[0] : 0;
        }

        if (index >= _images.Count || _lastResult == null)
        {
            return "nothing in the gallery: generate an image first";
        }

        if (_targetKind == null || _targetKind == AssetKind.Hue)
        {
            return "no static bound: bind a land tile, static or gump first";
        }

        theme = (theme ?? _themeName?.Text ?? "").Trim();
        if (theme.Length == 0)
        {
            return "name the theme first";
        }

        int variant = NextVariantId(theme);
        if (variant < 0)
        {
            return "no free variant id left in 0xF000-0xFEFF";
        }
        var prov = new ArtProvenance
        {
            Tool = "comfyui",
            Workflow = _lastWorkflow,
            Kind = "",
            Seed = _lastSeed >= 0 ? _lastSeed : null,
            DerivedFromClientArt = true,
        };
        prov.Inputs.Add($"client:{ArtSidecar.KindName(_targetKind.Value)}:0x{_targetId:X4}");

        var notes = new List<string>();
        string why = ArtExchange.ImportImage(_data, _targetKind.Value, variant, _images[index], prov, notes);
        if (why != null)
        {
            return $"refused: {why}";
        }

        AppendThemeEntry(theme, (ushort)_targetId, (ushort)variant);
        return $"saved {theme}: 0x{_targetId:X4} -> variant 0x{variant:X4} ({string.Join("; ", notes)})";
    }

    /// <summary>The next free variant id for a theme: 0xF000 up, skipping what the theme already uses.</summary>
    public int NextVariantId(string theme)
    {
        var used = new HashSet<int>();
        foreach (var e in ReadThemeEntries(theme))
        {
            used.Add(e.Variant);
        }

        for (int id = 0xF000; id < 0xFF00; id++)
        {
            if (!used.Contains(id) && !(_data?.Assets?.Has(AssetKind.Static, id) ?? false))
            {
                return id;
            }
        }

        return -1;
    }

    private List<(ushort Match, ushort Variant)> ReadThemeEntries(string theme)
    {
        var out_ = new List<(ushort, ushort)>();
        string path = Path.Combine(ThemeDir(_data), theme + ".theme.json");
        if (!File.Exists(path))
        {
            return out_;
        }

        try
        {
            JsonNode root = JsonNode.Parse(File.ReadAllText(path));
            if (root?["entries"] is JsonArray entries)
            {
                foreach (JsonNode e in entries)
                {
                    if (e?["match"] is JsonArray match && e["variant"] is JsonNode v)
                    {
                        foreach (JsonNode m in match)
                        {
                            out_.Add(((ushort)(int)m, (ushort)(int)v));
                        }
                    }
                }
            }
        }
        catch (Exception)
        {
        }

        return out_;
    }

    private void AppendThemeEntry(string theme, ushort match, ushort variant)
    {
        string dir = ThemeDir(_data);
        Directory.CreateDirectory(dir);
        string path = Path.Combine(dir, theme + ".theme.json");
        JsonObject root;
        JsonArray entries;
        try
        {
            root = File.Exists(path) && JsonNode.Parse(File.ReadAllText(path)) is JsonObject o ? o : new JsonObject();
            entries = root["entries"] as JsonArray ?? new JsonArray();
        }
        catch (Exception)
        {
            root = new JsonObject();
            entries = new JsonArray();
        }

        root["format"] = 1;
        root["name"] = theme;
        entries.Add(new JsonObject
        {
            ["match"] = new JsonArray(match),
            ["variant"] = variant,
        });
        root["entries"] = entries;
        if (root["multis"] == null)
        {
            root["multis"] = new JsonArray();
        }

        File.WriteAllText(path, root.ToJsonString(new System.Text.Json.JsonSerializerOptions { WriteIndented = true }));
    }

    // --- splats ------------------------------------------------------------------

    private void RefreshSplats()
    {
        _splatPick.Clear();
        foreach (string name in StagedSplatNames())
        {
            _splatPick.AddItem(name);
        }

        if (_splatPick.ItemCount == 0)
        {
            _splatPick.AddItem("(no staged splats: run tools/comfy/stage.py)");
            _splatPick.Disabled = true;
        }
        else
        {
            _splatPick.Disabled = false;
        }
    }

    /// <summary>Staged splat names from the manifest (or empty).</summary>
    public static List<string> StagedSplatNames()
    {
        var names = new List<string>();
        try
        {
            string stage = System.Environment.GetEnvironmentVariable("GUO_SPLAT_STAGE");
            if (string.IsNullOrWhiteSpace(stage))
            {
                stage = Path.Combine(EditorData.RepoRoot, "build", "staged", "guo-comfy-gen");
            }

            string manifest = Path.Combine(stage, "splats.json");
            if (File.Exists(manifest) && JsonNode.Parse(File.ReadAllText(manifest))?["splats"] is JsonObject splats)
            {
                foreach (var kv in splats)
                {
                    names.Add(kv.Key);
                }
            }
        }
        catch (Exception)
        {
        }

        return names;
    }

    /// <summary>Fills the placement fields from the world view centre (the player).</summary>
    public void FillCentre()
    {
        GUO.Game.World world = _world?.Invoke();
        if (world?.Player == null)
        {
            Report("no world open");
            return;
        }

        _placeX.Text = world.Player.X.ToString();
        _placeY.Text = world.Player.Y.ToString();
        _placeZ.Text = world.Player.Z.ToString();
    }

    /// <summary>
    /// Records a placement for the picked splat at the typed tile in
    /// the staged manifest (created if missing). The live scene and the editor
    /// world both draw it from there.
    /// </summary>
    public string PlaceSplat()
    {
        if (!int.TryParse(_placeX?.Text, out int x) || !int.TryParse(_placeY?.Text, out int y))
        {
            return "type the tile x,y first (or View centre)";
        }

        int z = int.TryParse(_placeZ?.Text, out int zz) ? zz : 0;
        string name = !_splatPick.Disabled ? _splatPick.GetItemText(_splatPick.Selected) : "";
        return PlaceSplatAt(name, x, y, z);
    }

    /// <summary>Placement core without the UI (the smoke check).</summary>
    public string PlaceSplatAt(string name, int x, int y, int z)
    {
        if (string.IsNullOrEmpty(name))
        {
            return "no staged splat to place";
        }

        try
        {
            string stage = System.Environment.GetEnvironmentVariable("GUO_SPLAT_STAGE");
            if (string.IsNullOrWhiteSpace(stage))
            {
                stage = Path.Combine(EditorData.RepoRoot, "build", "staged", "guo-comfy-gen");
            }

            Directory.CreateDirectory(stage);
            string manifest = Path.Combine(stage, "splats.json");
            JsonObject root = File.Exists(manifest) && JsonNode.Parse(File.ReadAllText(manifest)) is JsonObject o
                ? o : new JsonObject { ["format"] = "guo/comfy-splats@1" };
            JsonObject splats = root["splats"] as JsonObject ?? new JsonObject();
            JsonObject entry = splats[name] as JsonObject;
            if (entry == null)
            {
                return $"staged manifest has no splat named '{name}'";
            }

            entry["placement"] = new JsonObject { ["facet"] = 0, ["x"] = x, ["y"] = y, ["z"] = z };
            splats[name] = entry;
            root["splats"] = splats;
            File.WriteAllText(manifest, root.ToJsonString(new System.Text.Json.JsonSerializerOptions { WriteIndented = true }));
            return $"placed {name} at {x},{y},{z} (re-stage or re-open the world to see it)";
        }
        catch (Exception ex)
        {
            return $"could not write the staged manifest: {ex.Message}";
        }
    }

