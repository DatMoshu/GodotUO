    /// <summary>Activates the named theme over a parsed zone and repaints the world.</summary>
    public string ApplyZone()
    {
        return ApplyZone((_themeName?.Text ?? "").Trim(), _zone?.Text ?? "");
    }

    /// <summary>Zone apply without the UI (the smoke check).</summary>
    public string ApplyZone(string theme, string zoneText)
    {
        if (theme.Length == 0)
        {
            return "name the theme first";
        }

        string[] parts = zoneText.Split(',');
        if (parts.Length < 5
            || !int.TryParse(parts[0], out int f) || !int.TryParse(parts[1], out int x1)
            || !int.TryParse(parts[2], out int y1) || !int.TryParse(parts[3], out int x2)
            || !int.TryParse(parts[4], out int y2))
        {
            return "zone reads 'facet,x1,y1,x2,y2', e.g. 0,1424,1688,1444,1711";
        }

        string path = Path.Combine(ThemeDir(_data), theme + ".theme.json");
        if (!File.Exists(path))
        {
            return $"no theme file {path}: save a variant first";
        }

        GUO.Game.Managers.Theme themeData;
        try
        {
            themeData = GUO.Game.Managers.Theme.Load(path);
        }
        catch (Exception ex)
        {
            return $"could not read {path}: {ex.Message}";
        }

        GUO.Game.Managers.ThemeManager.Activate(themeData,
            new List<GUO.Game.Managers.ThemeZone> { new() { Facet = f, X1 = x1, Y1 = y1, X2 = x2, Y2 = y2 } });
        GUO.Game.World world = _world?.Invoke();
        if (world == null)
        {
            return $"theme {theme} armed (no world open to repaint)";
        }

        GUO.Game.Managers.ThemeManager.Reapply(world);
        return $"theme {theme} paints facet {f} {x1},{y1}-{x2},{y2}";
    }

    /// <summary>Clears every theme and repaints originals.</summary>
    public string ClearThemes()
    {
        GUO.Game.Managers.ThemeManager.Clear();
        GUO.Game.World world = _world?.Invoke();
        if (world != null)
        {
            GUO.Game.Managers.ThemeManager.Reapply(world);
        }

        return "themes cleared: originals restored";
    }

    /// <summary>Cancels running work; called before a reload or when the dock closes.</summary>
    public void Shutdown()
    {
        _cts.Cancel();
        _cts = new CancellationTokenSource();
    }
