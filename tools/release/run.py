"""Validate release identity and synchronize platform version fields (stdlib only)."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERSION = re.compile(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-(alpha|beta|rc)\.([1-9][0-9]*))?")

def identity(root, tag=None):
    data = json.loads((root / "version.json").read_text(encoding="utf-8"))
    version = data["version"]
    match = VERSION.fullmatch(version)
    if not match or any(int(n) > 65535 for n in match.group(1, 2, 3)):
        raise ValueError("version must be MAJOR.MINOR.PATCH[-alpha.N|-beta.N|-rc.N], components <= 65535")
    code = data["android_version_code"]
    if type(code) is not int or not 1 <= code <= 2100000000:
        raise ValueError("android_version_code must be an integer from 1 to 2100000000")
    if tag is not None and tag != "v" + version:
        raise ValueError(f"tag {tag!r} must match v{version}")
    return version, code

def expected(root, version, code):
    numeric = version.split("-")[0] + ".0"
    files = {"tools/msbuild/Version.props": (
        '<Project>\n  <!-- Generated by tools/release/run.py sync from version.json. -->\n'
        f'  <PropertyGroup><Version>{version}</Version><AssemblyVersion>{numeric}</AssemblyVersion>'
        f'<FileVersion>{numeric}</FileVersion></PropertyGroup>\n</Project>\n')}
    replacements = {
        "godot/GUO/project.godot": [(r'^config/version=.*$', f'config/version="{version}"')],
        "tools/android/export_presets.template.cfg": [(r'^version/code=.*$', f'version/code={code}'), (r'^version/name=.*$', f'version/name="{version}"')],
        "tools/windows/export_presets.template.cfg": [(r'^application/file_version=.*$', f'application/file_version="{numeric}"'), (r'^application/product_version=.*$', f'application/product_version="{numeric}"')],
    }
    for name, rules in replacements.items():
        text = (root / name).read_text(encoding="utf-8")
        for pattern, value in rules:
            if name.endswith("project.godot") and not re.search(pattern, text, re.M):
                text = text.replace("[application]", "[application]\n\n" + value)
            else:
                text, count = re.subn(pattern, lambda _: value, text, flags=re.M)
                if count != 1:
                    raise ValueError(f"expected one {pattern} in {name}")
        files[name] = text
    return files

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["check", "sync"])
    parser.add_argument("--tag")
    args = parser.parse_args()
    version, code = identity(ROOT, args.tag)
    for name, text in expected(ROOT, version, code).items():
        path = ROOT / name
        if args.command == "sync":
            path.write_text(text, encoding="utf-8", newline="\n")
        elif not path.exists() or path.read_text(encoding="utf-8") != text:
            raise ValueError(f"{name} is stale; run python tools/release/run.py sync")
    print(f"GUO {version}; Android code {code}; {args.command} passed")

if __name__ == "__main__":
    main()
