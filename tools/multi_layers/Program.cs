using GUO.Editor;
using System.Text.Json.Nodes;
int checks = 0;
void Check(bool ok, string name) { if (!ok) throw new Exception(name); checks++; Console.WriteLine("PASS " + name); }
void Reject(Action action, string name) { bool failed = false; try { action(); } catch (ArgumentException) { failed = true; } catch (InvalidOperationException) { failed = true; } Check(failed, name); }
var d = new MultiDocument();
d.Place(100, 0, 0, 7);
d.EditLayer(d.Revision, "create", 0, "Roof");
int roof = d.ActiveLayerId;
d.Place(200, 0, 0, 47);
Check(d.Parts.Last().LayerId == roof, "new parts use active layer");
long rev = d.Revision; int history = d.HistoryCount;
d.EditLayer(rev, "move", roof, dx: 2, apply: false);
Check(d.Revision == rev && d.HistoryCount == history && d.Parts.Last().X == 0, "preview is nonmutating");
d.EditLayer(rev, "move", roof, dx: 2);
Check(d.Parts.Last().X == 2 && d.Parts.First().X == 0, "move scoped to roof");
Reject(() => d.EditLayer(rev, "move", roof, dx: 1), "stale revision rejected");
d.Undo(); Check(d.Parts.Last().X == 0, "move undo"); d.Redo();
d.EditLayer(d.Revision, "lock", roof, value: true);
var before = d.Parts.ToArray(); history = d.HistoryCount;
Check(!d.Move(d.Parts.Select(p => p.Uid), 3, 0, 0), "manual move blocked by lock");
Check(d.Parts.Zip(before).All(p => p.First.SameAs(p.Second)) && d.HistoryCount == history, "mixed locked edit rolls back atomically");
Reject(() => d.EditLayer(d.Revision, "replace", roof, tile: 200, replacement: 201), "AI replacement blocked by lock");
d.EditLayer(d.Revision, "visible", roof, value: false);
Check(!d.LayerVisible(roof) && d.Parts.Last().Shown, "editor hide preserves export flags");
d.Undo(); Check(d.LayerVisible(roof), "layer metadata undo");
d.Redo(); Check(!d.LayerVisible(roof), "layer metadata redo");
var json = MultiLayerCodec.Encode(d, "{\"kind\":\"components\",\"components\":[]}");
var parts = d.Parts.ToList();
var layers = MultiLayerCodec.Decode(json, parts);
var reopened = new MultiDocument(); reopened.Reset(parts, "reopen", layers);
Check(reopened.Layers.SequenceEqual(d.Layers) && reopened.Parts.Zip(d.Parts).All(p => p.First.SameAs(p.Second)), "layer and membership roundtrip");
Check(MultiLayerCodec.Decode("{\"kind\":\"components\"}", parts).Count == 1, "legacy description defaults to one layer");
var invalid = JsonNode.Parse(json); invalid["editor_layers"]["membership"] = new JsonArray(99);
Reject(() => MultiLayerCodec.Decode(invalid.ToJsonString(), parts), "invalid membership rejected");
d.EditLayer(d.Revision, "lock", roof, value: false);
Reject(() => d.EditLayer(d.Revision, "move", roof, dx: int.MaxValue), "coordinate overflow rejected");
d.EditLayer(d.Revision, "select", roof);
d.EditLayer(d.Revision, "assign", 0);
Check(d.Parts.All(p => p.LayerId == 0), "assign selected components");
d.Undo(); Check(d.Parts.Last().LayerId == roof, "assignment undo");
d.EditLayer(d.Revision, "replace", roof, tile: 200, replacement: 201);
Check(d.Parts.Last().Id == 201 && d.Parts.First().Id == 100, "material replacement scoped");
d.LoadGeneration(MultiLayerCodec.ReadGeneration("{\"generation\":{\"source_id\":\"fixture\",\"source_rooms\":[{\"id\":7}]}}"));
var savedGeneration = MultiLayerCodec.Encode(d, "{\"components\":[]}");
Check(JsonNode.Parse(savedGeneration)["generation"]["source_rooms"][0]["id"].GetValue<int>() == 7, "source room provenance survives save");
Reject(() => MultiLayerCodec.ReadGeneration("{\"generation\":[]}"), "invalid provenance refused");
d.Reset(Array.Empty<MultiPart>(), "new");
Check(d.GenerationJson == null, "new document clears source provenance");
foreach (string malformed in new[] { "null", "[]", "42", "\"bad\"" })
    Reject(() => MultiLayerCodec.Decode("{\"editor_layers\":" + malformed + "}", new()), "malformed layer metadata rejected: " + malformed);
Reject(() => MultiLayerCodec.Decode("{\"editor_layers\":{\"version\":1,\"layers\":[null],\"membership\":[]}}", new()), "null layer record rejected");
var nearLimit = new MultiDocument();
nearLimit.Reset(Array.Empty<MultiPart>(), "import", new[] { new MultiLayer(int.MaxValue - 1, "Imported") });
long nearRevision = nearLimit.Revision;
Reject(() => nearLimit.EditLayer(nearRevision, "create", 0, "New"), "exhausted layer ID creation refused");
Check(nearLimit.Revision == nearRevision && nearLimit.Layers.Count == 1, "exhausted creation is atomic");
nearLimit.EditLayer(nearLimit.Revision, "rename", int.MaxValue - 1, "Renamed");
Check(nearLimit.Layers.Single().Name == "Renamed", "near-limit imported layer remains editable");
Console.WriteLine($"{checks} checks passed");
